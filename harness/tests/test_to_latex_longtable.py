"""Tests for the converter's long-table continuations (paper/tools/to_latex.py): proof 5's supplement printed "Table Sn: CAPTION"
under four continued panels and gave each a new number (B2 scan, MUST 1). Synthetic table files only; no data needed.
"""

import importlib.util
import os
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
if not (REPO / "paper" / "tools" / "to_latex.py").is_file():
    raise unittest.SkipTest("paper/tools/to_latex.py is not in the released package (the paper's source goes to arXiv)")
_spec = importlib.util.spec_from_file_location("to_latex", REPO / "paper" / "tools" / "to_latex.py")
to_latex = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(to_latex)

CAP_LINE = "\\caption{\u27e6CAPTION\u27e7}\\label{\u27e6LABEL\u27e7}\\\\\n"


def _longtable(cid, panel=None):
    head = f"% TAB-{cid} panel {panel}: Panel title: generated by harness/analysis/paper_outputs.py; do not edit\n" if panel else ""
    return ("% layout: longtable\n" + head + "\\begin{xltabular}{\\linewidth}{lX}\n" + CAP_LINE
            + "\\toprule\nA & B \\\\\n\\midrule\n\\endfirsthead\n\\endhead\n1 & 2 \\\\\n\\end{xltabular}\n")


class Continuation(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.outputs = os.path.join(self.tmp.name, "outputs")
        self.tables = os.path.join(self.tmp.name, "build", "tables")
        os.makedirs(self.outputs)
        os.makedirs(self.tables)
        open(os.path.join(self.outputs, "TAB-99.tex"), "w", encoding="utf-8").write(_longtable("99"))
        open(os.path.join(self.outputs, "TAB-99.panel1.tex"), "w", encoding="utf-8").write(_longtable("99", 1))
        for f in os.listdir(self.outputs):  # build_overleaf.py copies the raw files first; to_latex.py rewrites what it resolves
            Path(self.tables, f).write_text(Path(self.outputs, f).read_text(encoding="utf-8"), encoding="utf-8")
        self.saved = (to_latex.OUT_TABLES, to_latex.SUPPLEMENT, to_latex.ANON)
        to_latex.OUT_TABLES, to_latex.SUPPLEMENT, to_latex.ANON = self.tables, True, False

    def tearDown(self):
        to_latex.OUT_TABLES, to_latex.SUPPLEMENT, to_latex.ANON = self.saved
        self.tmp.cleanup()

    def build(self):
        return to_latex.redesigned_table("TAB-99", ["TAB-99", "TAB-99.panel1"], "The caption", "tab:TAB-99", "longtable",
                                         self.outputs)

    def test_the_continued_panel_is_written_without_the_placeholder_caption(self):
        self.build()
        panel = Path(self.tables, "TAB-99.panel1.tex").read_text(encoding="utf-8")
        self.assertNotIn("\u27e6", panel)
        self.assertNotIn("\\caption", panel)
        main = Path(self.tables, "TAB-99.tex").read_text(encoding="utf-8")
        self.assertIn("\\caption{The caption}\\label{tab:TAB-99}", main)

    def test_the_continued_panel_keeps_the_parent_number(self):
        # in this build a long table with no \caption takes no number (proof 5, supplement p. 52: TAB-26's panel prints
        # "Table S11 (continued)" and the next table is S12), so the head prints the parent's number and nothing moves the counter
        tex = self.build()
        cont = tex[tex.index("% longtable-continued"):]
        self.assertIn("\\tablename~\\thetable: (continued)", cont.split("\\input{tables/TAB-99.panel1}")[0])
        self.assertNotIn("addtocounter{table}", cont)
        self.assertEqual(tex.count("\\caption{"), 0)  # the parent's caption is in its table file, the panel's is gone


if __name__ == "__main__":
    unittest.main()
